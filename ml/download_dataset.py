"""
Download authentic CIFAKE dataset directly from Jordan Bird's official repository:
https://github.com/jordan-bird/CIFAKE-Real-and-AI-Generated-Synthetic-Images

CIFAKE contains:
  - REAL: 60,000 real CIFAR-10 photographs
  - FAKE: 60,000 synthetic images generated by Stable Diffusion v1.4

Downloads images via multi-threaded concurrent requests directly from official raw GitHub storage.
NO procedural/synthetic mathematical placeholder fallbacks.
"""

import os
import sys
import json
import urllib.request
import concurrent.futures
from PIL import Image
from tqdm import tqdm

DATASET_DIR = os.path.join(os.path.dirname(__file__), "cifake_dataset")
GITHUB_API_BASE = "https://api.github.com/repos/jordan-bird/CIFAKE-Real-and-AI-Generated-Synthetic-Images/contents/DATASET"
RAW_BASE = "https://raw.githubusercontent.com/jordan-bird/CIFAKE-Real-and-AI-Generated-Synthetic-Images/main/DATASET"


def fetch_file_list(split: str, label: str):
    """Fetch list of image filenames from GitHub API for a given split/label."""
    url = f"{GITHUB_API_BASE}/{split}/{label}?per_page=100"
    headers = {
        "User-Agent": "Mozilla/5.0 (Macintosh; Intel Mac OS X 10_15_7)",
        "Accept": "application/vnd.github.v3+json"
    }
    
    files = []
    try:
        # Request file tree from GitHub API
        req = urllib.request.Request(url, headers=headers)
        with urllib.request.urlopen(req, timeout=15) as res:
            items = json.loads(res.read())
            for item in items:
                if item.get("name", "").endswith((".jpg", ".png", ".jpeg")):
                    files.append(item["name"])
    except Exception as e:
        print(f"GitHub API list error for {split}/{label}: {e}")
    
    return files


def download_single_file(args):
    """Download a single image file from raw GitHub storage."""
    split, label, filename, dest_dir = args
    dest_path = os.path.join(dest_dir, filename)
    
    if os.path.exists(dest_path) and os.path.getsize(dest_path) > 100:
        return True
    
    # URL encode spaces in filename
    encoded_name = urllib.parse.quote(filename)
    raw_url = f"{RAW_BASE}/{split}/{label}/{encoded_name}"
    
    headers = {"User-Agent": "Mozilla/5.0 (Macintosh; Intel Mac OS X 10_15_7)"}
    try:
        req = urllib.request.Request(raw_url, headers=headers)
        with urllib.request.urlopen(req, timeout=10) as response, open(dest_path, "wb") as f:
            f.write(response.read())
        return True
    except Exception as e:
        if os.path.exists(dest_path):
            os.remove(dest_path)
        return False


def download_category(split: str, label: str, target_count: int = 2500):
    """Download authentic images for split/label using concurrent threads."""
    dest_dir = os.path.join(DATASET_DIR, split, label)
    os.makedirs(dest_dir, exist_ok=True)
    
    existing = len([f for f in os.listdir(dest_dir) if f.endswith(('.jpg', '.png'))])
    if existing >= target_count:
        print(f"  {split}/{label}: {existing} authentic images already present.")
        return
    
    print(f"\nFetching official file list for {split}/{label}...")
    filenames = fetch_file_list(split, label)
    
    if not filenames:
        print(f"  Failed to fetch list for {split}/{label}. Trying direct index generation...")
        # Fallback to direct naming format: 0000 (1).jpg up to target_count
        filenames = [f"{i:04d} ({j}).jpg" for i in range(10) for j in range(1, 300)]
    
    filenames = filenames[:target_count]
    print(f"Downloading {len(filenames)} authentic images for {split}/{label}...")
    
    tasks = [(split, label, fn, dest_dir) for fn in filenames]
    
    successful = 0
    with concurrent.futures.ThreadPoolExecutor(max_workers=16) as executor:
        results = list(tqdm(
            executor.map(download_single_file, tasks),
            total=len(tasks),
            desc=f"Downloading {split}/{label}"
        ))
        successful = sum(1 for r in results if r)
    
    print(f"  Completed {split}/{label}: {successful}/{len(filenames)} images downloaded.")


def print_stats():
    """Print dataset statistics and verify sample sizes."""
    print(f"\n{'='*60}")
    print("Authentic CIFAKE Dataset Statistics:")
    print(f"{'='*60}")
    total_images = 0
    for split in ["train", "test"]:
        for label in ["REAL", "FAKE"]:
            class_dir = os.path.join(DATASET_DIR, split, label)
            if os.path.exists(class_dir):
                count = len([f for f in os.listdir(class_dir) if f.endswith(('.jpg', '.png'))])
                print(f"  {split}/{label}: {count} authentic images")
                total_images += count
    print(f"Total Authentic Images: {total_images}")
    print(f"{'='*60}\n")


def main():
    print(f"\n{'='*60}")
    print("Downloading Official Authentic CIFAKE Dataset from GitHub")
    print("Source: jordan-bird/CIFAKE-Real-and-AI-Generated-Synthetic-Images")
    print(f"{'='*60}")
    
    os.makedirs(DATASET_DIR, exist_ok=True)
    
    # Download authentic training set (2000 real photos, 2000 fake AI images)
    download_category("train", "REAL", target_count=2000)
    download_category("train", "FAKE", target_count=2000)
    
    # Download authentic test set (500 real photos, 500 fake AI images)
    download_category("test", "REAL", target_count=500)
    download_category("test", "FAKE", target_count=500)
    
    print_stats()


if __name__ == "__main__":
    main()
